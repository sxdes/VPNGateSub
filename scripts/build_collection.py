#!/usr/bin/env python3
"""Build the public grouped subscription without exposing upstream URLs."""

import json
import re
from pathlib import Path

SOURCE = Path("output/mihomo.yaml")
DESTINATION = Path("output/collection.yaml")
SOURCE_NAME = "VPNGate"

def yaml_quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)

def extract_proxies(text: str) -> tuple[list[str], list[str]]:
    try:
        section = text.split("\nproxies:\n", 1)[1].split("\nproxy-groups:\n", 1)[0]
    except IndexError as exc:
        raise SystemExit("source config has no proxies section") from exc
    matches = list(re.finditer(r'^  - name: "((?:\\.|[^"\\])*)"$', section, re.M))
    if not matches:
        raise SystemExit("source config contains no named proxies")
    blocks, names = [], []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(section)
        original = json.loads(f'"{match.group(1)}"')
        name = f"{SOURCE_NAME} | {original}"
        block = section[match.start():end]
        block = block.replace(match.group(0), f"  - name: {yaml_quote(name)}", 1).rstrip()
        blocks.append(block)
        names.append(name)
    return blocks, names

def build(blocks: list[str], names: list[str]) -> str:
    lines = [
        "# Grouped public collection generated by GitHub Actions.",
        "mixed-port: 7890", "allow-lan: false", "mode: rule", "log-level: info",
        "ipv6: false", "unified-delay: true", "tcp-concurrent: true",
        "profile:", "  store-selected: true", "", "proxies:", *blocks, "",
        "proxy-groups:",
        "  - name: 节点选择", "    type: select", "    proxies:",
        f"      - {SOURCE_NAME}", "      - DIRECT",
        f"  - name: {SOURCE_NAME}", "    type: select", "    proxies:",
        f"      - {SOURCE_NAME}-AUTO",
        *[f"      - {yaml_quote(name)}" for name in names],
        f"  - name: {SOURCE_NAME}-AUTO", "    type: url-test",
        "    url: https://www.gstatic.com/generate_204", "    interval: 300",
        "    tolerance: 50", "    proxies:",
        *[f"      - {yaml_quote(name)}" for name in names],
        "", "rules:", "  - MATCH,节点选择", "",
    ]
    result = "\n".join(lines)
    if "proxy-providers:" in result or "vpngate.net" in result or "raw.githubusercontent.com" in result:
        raise SystemExit("generated collection leaks an upstream URL")
    return result

def main() -> None:
    blocks, names = extract_proxies(SOURCE.read_text(encoding="utf-8"))
    DESTINATION.write_text(build(blocks, names), encoding="utf-8")
    print(f"wrote {DESTINATION} with {len(names)} {SOURCE_NAME} nodes")

if __name__ == "__main__":
    main()
